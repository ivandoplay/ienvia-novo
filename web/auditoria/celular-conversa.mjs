import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
const BASE='http://127.0.0.1:3100';
const env = Object.fromEntries(readFileSync('/home/user/.env','utf8').split('\n').map(l=>l.match(/^([A-Z0-9_]+)=(.*)$/)).filter(Boolean).map(m=>[m[1],m[2].trim()]));
const b=await chromium.launch(); const p=await (await b.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2,locale:'pt-BR'})).newPage();
await p.goto(`${BASE}/login`,{waitUntil:'networkidle'});
await p.getByLabel(/usuário|usuario|e-mail|email/i).first().fill(env.TESTE_USUARIO);
await p.getByLabel(/senha/i).first().fill(env.TESTE_SENHA);
await p.getByRole('button',{name:/entrar|acessar/i}).first().click(); await p.waitForTimeout(2200);
await p.goto(`${BASE}/inbox`,{waitUntil:'networkidle'}); await p.waitForTimeout(1200);
await p.screenshot({path:'/home/user/ienvia/auditoria-visual/inbox/11-celular-lista-prod.png'});
await p.locator('button, [role="button"], li, a').filter({hasText:'Lucas Martins'}).first().click();
await p.waitForTimeout(2500);
await p.screenshot({path:'/home/user/ienvia/auditoria-visual/inbox/12-celular-conversa-prod.png'});
const m = await p.evaluate(`(() => {
  const main=document.querySelector('main');
  const thread=[...document.querySelectorAll('main *')].filter(e=>e.childElementCount===0&&e.textContent.trim()).map(e=>({c:String(e.className).slice(0,30), t:e.textContent.trim().slice(0,50), h:Math.round(e.getBoundingClientRect().height)}));
  return { url: location.href, altura: document.documentElement.scrollHeight, itens: thread.slice(0, 18) };
})()`);
console.log(JSON.stringify(m,null,1));
await b.close();

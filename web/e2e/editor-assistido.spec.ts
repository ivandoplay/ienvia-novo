import {test,expect} from '@playwright/test';
import {entrar} from './apoio/sessao';
import {BASE_PRINCIPAL_DA_INBOX} from './apoio/ia-no-banco-falso.mjs';
const api='http://127.0.0.1:54399',ia='http://127.0.0.1:54397';
test.beforeEach(async({request})=>{await request.post(api+'/controle/reiniciar-ia');await request.post(ia+'/controle/reiniciar');});
test('página Next autenticada: proposta, confirmação, persistência e desfazer',async({page,request},info)=>{
 await entrar(page,'inbox');await page.goto('/treinamento');
 await page.getByRole('tab',{name:'Editar com IA'}).click();
 const text=page.getByRole('textbox',{name:'Mensagem para o editor'});
 await expect(text).toBeEnabled();
 await expect.poll(()=>page.getByRole('tab',{name:'Editar com IA'}).evaluate(el=>{const a=el.getBoundingClientRect(),b=el.parentElement!.getBoundingClientRect();return a.left>=b.left-1&&a.right<=b.right+1;})).toBe(true);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await request.post(ia+'/controle/proxima-resposta',{data:{texto:JSON.stringify({resposta:'Preparei um ajuste nas regras. Revise antes de aprovar.',alteracoes:[{resource:'treinamento',id:BASE_PRINCIPAL_DA_INBOX,field:'golden_rules',value:'Seja direto e confirme as informações antes de responder.'}]})}});
 await text.fill('Deixe as regras mais diretas.');await page.getByRole('button',{name:'Enviar ↑'}).click();
 await expect(page.getByRole('button',{name:'Aplicar alterações'})).toBeVisible();
 await page.locator('.treino-chat-proposta summary').click();
 await expect(page.getByText('Seja direto e confirme as informações antes de responder.',{exact:true})).toBeVisible();
 await page.screenshot({path:`.cache/evidencias/editor-ia/next-${info.project.name}-revisao.png`,fullPage:true});
 await page.getByRole('button',{name:'Aplicar alterações'}).click();
 await expect(page.getByRole('button',{name:'Desfazer alterações'})).toBeVisible();
 await page.getByRole('tab',{name:'Regras',exact:true}).click();
 await expect(page.getByLabel('Regras de ouro')).toHaveValue('Seja direto e confirme as informações antes de responder.');
 await page.getByRole('tab',{name:'Editar com IA'}).click();
 await page.getByRole('button',{name:'Conversas',exact:true}).click();
 await page.getByRole('button',{name:/Deixe as regras mais diretas/}).click();
 await page.getByRole('button',{name:'Desfazer alterações'}).click();
 await expect(page.getByText('Alterações desfeitas. A revisão anterior foi restaurada.')).toBeVisible();
 await page.reload();await page.getByRole('tab',{name:'Regras',exact:true}).click();
 await expect(page.getByLabel('Regras de ouro')).not.toHaveValue('Seja direto e confirme as informações antes de responder.');
});
